#!/usr/bin/env python3
"""Regenerate the parts of the card and the provenance that list every layer.

Reads data/raw/<version>/MANIFEST.json, data/parquet/<version>/LAYERS.json
(03_export_parquet.py) and data/work/<version>/VERIFY.json (02_verify.py),
and rewrites only:

  data/README.md        the `configs:` list of the YAML front matter (one
                        subset per layer, named after it), and the table
                        between <!-- layers:start --> and <!-- layers:end -->
  data/provenance.yaml  everything after the line MARKER

The hand-written rest of both files is left as it is.

    uv run python scripts/04_card.py
"""

import importlib.util
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "data"
MARKER = "# --- below this line is generated by scripts/04_card.py ---"
DEFAULT = "ne_10m_admin_0_countries"

_spec = importlib.util.spec_from_file_location("publish", ROOT / "src" / "publish.py")
publish = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(publish)


def configs(version: str, layers: dict) -> str:
    out = ""
    for name, x in sorted(layers.items(), key=lambda kv: kv[1]["file"]):
        group = f"{x['scale']}_{x['category']}"
        out += publish.subset_entry(version, group, name)
        if name == DEFAULT:
            out += "  default: true\n"
    return out


def replace_configs(card: str, block: str) -> str:
    head, sep, rest = card.partition("configs:\n")
    if not sep:
        raise SystemExit("data/README.md has no 'configs:' in its front matter")
    end = rest.index("---\n")
    return head + sep + block + rest[end:]


def replace_between(text: str, start: str, end: str, body: str) -> str:
    i, j = text.index(start) + len(start), text.index(end)
    return text[:i] + "\n" + body + text[j:]


def table(layers: dict, verify: dict) -> str:
    rows = [
        "| layer | features | fields | geometry | invalid | version | zip |",
        "|---|---:|---:|---|---:|---|---|",
    ]
    for name, x in sorted(layers.items(), key=lambda kv: kv[1]["file"]):
        g = verify.get(name, {}).get("geometry", {})
        types = ", ".join(f"{t} {n:,}" for t, n in g.get("types", {}).items())
        src = "own" if x["source"] == "layer" else Path(x["zip"]).name
        rows.append(
            f"| {name} | {x['features']:,} | {x['fields']} | {types} | {g.get('invalid', '?')} "
            f"| {x['declared_version'] or 'none'} | {src} |"
        )
    return "\n".join(rows) + "\n"


def yaml_str(s) -> str:
    return json.dumps(s, ensure_ascii=False)


def provenance(version: str, man: dict, layers: dict, verify: dict) -> str:
    out = [MARKER, "", f"layers_{version.replace('.', '_')}:"]
    for name, x in sorted(layers.items(), key=lambda kv: kv[1]["file"]):
        e = man["files"][x["zip"]]
        g = verify.get(name, {}).get("geometry", {})
        out += [
            f"  {name}:",
            f"    zip: {x['zip']}",
            f"    source: {x['source']}",
            f"    zip_sha256: {e['sha256']}",
            f"    zip_last_modified: {yaml_str(e['last_modified'])}",
            f"    declared_version: {yaml_str(x['declared_version'])}",
            f"    page_version: {yaml_str((e.get('page') or {}).get('page_version'))}",
            f"    encoding: {yaml_str(x['encoding_how'])}",
            f"    features: {x['features']}",
            f"    fields: {x['fields']}",
            f"    geometry_types: {yaml_str(g.get('types'))}",
            f"    geometry_invalid: {g.get('invalid')}",
            f"    geometry_null: {g.get('null')}",
            f"    geometry_empty: {g.get('empty')}",
            f"    parquet: {{file: parquet/{x['file']}, bytes: {x['parquet_bytes']}}}",
        ]
    return "\n".join(out) + "\n"


def main() -> int:
    mpaths = sorted((DATA / "raw").glob("*/MANIFEST.json"))
    if len(mpaths) != 1:
        raise SystemExit(f"expected one version under data/raw/, found {len(mpaths)}")
    version = mpaths[0].parent.name
    man = json.loads(mpaths[0].read_text())
    layers = json.loads((DATA / "parquet" / version / "LAYERS.json").read_text())
    verify = json.loads((DATA / "work" / version / "VERIFY.json").read_text())

    card_path = DATA / "README.md"
    card = replace_configs(card_path.read_text(encoding="utf-8"), configs(version, layers))
    card = replace_between(
        card, "<!-- layers:start -->", "<!-- layers:end -->", table(layers, verify)
    )
    card_path.write_text(card, encoding="utf-8")

    prov_path = DATA / "provenance.yaml"
    prov = prov_path.read_text(encoding="utf-8")
    head = prov[: prov.index(MARKER)] if MARKER in prov else prov.rstrip("\n") + "\n\n"
    prov_path.write_text(head + provenance(version, man, layers, verify), encoding="utf-8")
    print(f"{version}: {len(layers)} layers written to data/README.md and data/provenance.yaml")
    return 0


if __name__ == "__main__":
    sys.exit(main())
